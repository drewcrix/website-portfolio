// Scripted responses for the portfolio guide. 
//
// Each intent has `patterns` (keywords/phrases or RegExps matched against the
// visitor's normalised message), a `weight` used to break ties between intents,
// and a `reply(ctx)` that returns { text, actions?, navigate? }.
//
// Actions are rendered as buttons:
//   { label, intent }            -> runs another intent (e.g. 'projects' or 'project:thesis')
//   { label, href, external? }   -> plain link (PDFs, mailto:, other sites)
//
// Project-specific answers are generated from src/data/projects.json, so new
// projects become discoverable by the chatbot automatically.

export const guide = {
  name: 'Buddy Bot',
  tagline: 'Ask me a question',
}

export const mainActions = [
  { label: 'View Projects', intent: 'projects' },
  { label: 'About Drew', intent: 'about' },
  { label: 'Research', intent: 'research' },
  { label: 'Contact', intent: 'contact' },
  { label: 'View Resume', intent: 'resume' },
]

export const greeting = {
  text: "Hey! Welcome to Drew's portfolio! 👋 I'm here to help you explore his projects, experience, and research. What would you like to see?",
  actions: mainActions,
}

